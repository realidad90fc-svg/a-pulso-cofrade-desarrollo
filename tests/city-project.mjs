import assert from 'node:assert/strict';
import {createCityProject,addCityMap,addCityZone,assignCityZone,searchCityStreets,indexMapStreets,affectedBrotherhoods,resolveCityMap,exportCityBundle,validateCityBundle,validateMapDocument,normalizeStreet} from '../city-project.mjs';
const project=createCityProject(),docs=new Map();
const a=addCityMap(project,{name:'Arfe y Adriano',barrio:'Arenal'});docs.set(a.meta.key,a.document);
const b=addCityMap(project,{name:'Continuación',barrio:'Arenal'});docs.set(b.meta.key,b.document);
a.document.roads.push({poly:[[0,0],[10,0],[10,4],[0,4]],material:'road-art-granite'});
a.document.labels.push(['Adriano',[4,2]],['O’Donnell',[8,2]]);indexMapStreets(project,a.document);
const zone=addCityZone(project,a.meta.key,'Adriano · Baratillo',[1,0,9,4],['Adriano']);
assert(assignCityZone(project,'esperanza-puente',zone.id).added);
assert(!assignCityZone(project,'esperanza-puente',zone.id).added);
assignCityZone(project,'otra-hermandad',zone.id);
assert.equal(project.itineraries['esperanza-puente'].length,1);
assert.deepEqual(affectedBrotherhoods(project,a.meta.key),['esperanza-puente','otra-hermandad']);
assert.equal(searchCityStreets(project,'adriáno')[0].name,'Adriano');
assert.equal(searchCityStreets(project,"O'Donnell")[0].name,'O’Donnell');
assert.equal(normalizeStreet('  O’DONNELL '),'odonnell');
b.document.zoneRefs=[{zoneId:zone.id,offset:[10,5],angle:90}];
const before=structuredClone(a.document),resolved=resolveCityMap(project,b.meta.key,k=>docs.get(k));
assert.deepEqual(a.document,before,'Resolving a shared street must not change the canonical map');
assert.equal(resolved.roads.length,1);assert.deepEqual(resolved.roads[0].poly[0],[10,5]);
a.document.roads[0].material='road-sev-espiga';
assert.equal(resolveCityMap(project,b.meta.key,k=>docs.get(k)).roads[0].material,'road-sev-espiga','A shared edit must reach every reference');
const bundle=exportCityBundle(project,k=>docs.get(k));assert.deepEqual(validateCityBundle(JSON.parse(JSON.stringify(bundle))).project,project);
project.itineraries['esperanza-puente'].splice(0,1);assert(docs.has(a.meta.key),'Detaching an itinerary must preserve the source map');
a.document.zoneRefs=[{zoneId:'map:'+b.meta.key,offset:[0,0],angle:0}];
assert.throws(()=>resolveCityMap(project,b.meta.key,k=>docs.get(k)),/circular/);
delete a.document.zoneRefs;
assert.throws(()=>addCityMap(project,{name:'Arfe y Adriano'}),/existe/);
assert.throws(()=>validateMapDocument({...a.document,roads:[{poly:[[0,0],[Infinity,1],[2,2]]}]}),/polígonos/);
assert.throws(()=>validateCityBundle({...bundle,documents:{}}),/mapa/);
console.log('PASS city: reusable maps/zones, two brotherhoods, deduplication, accent/alias search, reference updates, rotation, export/reopen, unlink preservation, invalid import and circular links.');

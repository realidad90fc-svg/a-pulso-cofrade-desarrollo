import assert from 'node:assert/strict';
import {StreetIdentifiers} from '../street-identifiers.mjs';
const labels=[['Arfe',[10,0],{radius:1}],['Adriano',[20,0],{radius:.5}],['Pastor y Landero',[30,0]]];
const streets=new StreetIdentifiers(labels);
assert.equal(streets.at([0,0],0),null,'No name before reaching an announcement point, even if it is the nearest street');
assert.equal(streets.at([9,2],1),null,'Passing outside the configured radius must not trigger');
assert.equal(streets.at([10,0],2).name,'Arfe');
assert.equal(streets.at([16,0],3).name,'Arfe','Keep the last triggered street; proximity to the next must not announce it');
assert.equal(streets.at([19.4,0],4).name,'Arfe','Respect the edited small activation radius');
assert.equal(streets.at([20,0],5).name,'Adriano');
assert.equal(streets.at([20.1,0],6).since,5,'Staying on a point must not restart the announcement every frame');
assert.equal(streets.at([24,0],7).name,'Adriano');
assert.equal(streets.at([32,0],8).name,'Pastor y Landero','Crossing a point between frames must trigger');
assert.equal(streets.at([0,0],9).name,'Arfe','On the return trip, crossing points updates the street in traversal order');
const saved=JSON.parse(JSON.stringify(streets.snapshot())),restored=new StreetIdentifiers(labels);restored.restore(saved);
assert.deepEqual(restored.at([0,0],9),streets.notice,'Restoring outside every trigger must keep the saved active name');
const renamed=new StreetIdentifiers([['Nombre corregido',[10,0],{radius:1}]]);renamed.restore(saved);
assert.equal(renamed.at([0,0],9),null,'A renamed or removed point cannot restore an outdated name');
assert.equal(renamed.at([10,0],10).name,'Nombre corregido');
const empty=new StreetIdentifiers([]);empty.restore(saved);assert.equal(empty.at([10,0],11),null,'Deleting every point leaves no editor announcements');
const repeats=new StreetIdentifiers([['Arfe',[0,0]],['Arfe',[5,0]],['Adriano',[10,0]]]);
repeats.at([0,0],1);assert.equal(repeats.at([5,0],2).since,1,'Several points with the same street name must not spam the banner');
console.log('PASS street points: no nearest-name guesses, editable radius, ordered crossings, retained active street, no repeated banners, snapshots and renamed/deleted points.');

export function applyContentNames(layouts){
 for(const node of Object.values(layouts.nodes)){if(!node.text)continue;let text=node.text.text;
  for(const step of CONTENT_STEPS)for(const name of step.legacyNames){if(text===name||text===name+':')text=step.name+(text.endsWith(':')?':':'');}
  node.text.text=text;
 }
}
export function brotherhoodStatus(data,progress,id){
 if(!progress.unlocked.brotherhoods.includes(id))return 'BLOQUEADA';
 const routes=data.routes.filter(r=>r.brotherhoodId===id&&r.playable!==false);
 if(!routes.length)return 'PRÓXIMAMENTE';
 const total=progress.totals.brotherhoods[id];
 if(total.max>0&&total.stars===total.max)return 'PERFECTA';
 if(routes.every(r=>progress.records[r.id]?.completed))return 'COMPLETADA';
 return 'DISPONIBLE';
}

